"""Collect every robot run of a scene into one table (<runs>/navigation/RESULTS_<scene>.md and .json): verdict,
confidence, footprint used, sim / wall time, path length, share of the room seen, room description at the end, film and
summary paths.

    python -m whatchanged.navigation.collect --scene config1
"""

from __future__ import annotations

import argparse

import numpy as np

from whatchanged.common.io import read_json, write_json
from whatchanged.navigation.common import RUNS, nav_dir


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scene", required=True)
    a = ap.parse_args()
    rows = []
    for d in sorted((nav_dir(a.scene) / "runs").iterdir()):
        if not (d / "log.json").exists():
            continue
        L = read_json(d / "log.json")
        tr = np.array(L["trace"])
        room = [e["text"] for e in L["events"] if e["kind"] == "room"]
        rows.append(
            dict(
                run=d.name,
                world=L["world"],
                prompt=L["prompt"],
                name=L["task"]["name"],
                verdict=L["verdict"]["kind"],
                text=L["verdict"]["text"],
                conf=L["verdict"].get("conf"),
                radius=L["radius_m"],
                sim_s=L["sim_s"],
                wall_s=L["wall_s"],
                path_m=round(float(np.linalg.norm(np.diff(tr, axis=0), axis=1).sum()), 2) if len(tr) > 1 else 0.0,
                checked=L["final_belief"].get("checked"),
                seen=L["final_belief"].get("seen_frac"),
                names_target=L["task"]["name"] in L["verdict"]["text"],
                inventory_sha=L.get("inventory_sha"),
                room_end=room[-1] if room else "",
                video=L["video"],
                summary=L["summary"],
            )
        )
    RUNS.mkdir(parents=True, exist_ok=True)
    write_json(rows, RUNS / f"RESULTS_{a.scene}.json")
    lines = [
        f"# Navigation runs, scene {a.scene}",
        "",
        "Generated by whatchanged/navigation/collect.py from the per-run log.json files. "
        "No truth labels are read here.",
        "",
        "| run | prompt | target (inventory) | verdict | conf | footprint m | sim s | wall s | path m | room seen "
        "| verdict names target |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['run']} | {r['prompt']} | {r['name']} | {r['text']} | {min(0.99, r['conf'] or 0):.2f} | "
            f"{r['radius']} | {r['sim_s']:.0f} | {r['wall_s']:.0f} | {r['path_m']} | {100 * (r['seen'] or 0):.0f} % | "
            f"{'yes' if r['names_target'] else 'NO'} |"
        )
    lines += ["", "## Room description at the end of each run", ""] + [
        f"- **{r['run']}**: {r['room_end']}" for r in rows
    ]
    lines += ["", "## Files", ""] + [f"- {r['run']}: `{r['video']}`, `{r['summary']}`" for r in rows]
    (RUNS / f"RESULTS_{a.scene}.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[: len(rows) + 6]))


if __name__ == "__main__":
    main()
